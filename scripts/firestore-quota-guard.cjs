const fs = require('fs');

function patchFile(path, transform, label) {
  const source = fs.readFileSync(path, 'utf8');
  const next = transform(source);
  if (next !== source) {
    fs.writeFileSync(path, next, 'utf8');
    console.log(`[Firestore quota guard] Patched ${label}`);
  } else {
    console.log(`[Firestore quota guard] No change needed for ${label}`);
  }
}

// Keep Firestore data in the browser's persistent cache so normal reloads can
// reuse local data instead of rebuilding the whole listener result set.
patchFile('src/lib/firebase.ts', (source) => {
  let next = source.replace(
    'localCache: memoryLocalCache()\n',
    'localCache: persistentLocalCache({ tabManager: persistentMultipleTabManager() })\n'
  );
  next = next.replace(
    '  persistentSingleTabManager,\n',
    '  persistentSingleTabManager,\n  persistentMultipleTabManager,\n'
  );

  // The old startup connectivity probe was an unnecessary billed document read.
  next = next.replace(
    /\nasync function testConnection\(\) \{[\s\S]*?\n\}\n\ntestConnection\(\);\s*$/,
    '\n'
  );

  return next;
}, 'firebase cache/startup probe');

// Skip exact duplicate saves created by state re-hydration/autosave cycles.
// updated_at is intentionally ignored because it is generated by the save path.
patchFile('src/lib/firestoreService.ts', (source) => {
  const marker = 'function createSubscription(collName: string) {';
  const helper = `const recentFirestoreWrites = new Map<string, string>();

function stableFirestoreValue(value: any): any {
  if (Array.isArray(value)) return value.map(stableFirestoreValue);
  if (value && typeof value === 'object') {
    return Object.keys(value).sort().reduce((out: any, key) => {
      if (key !== 'updated_at') out[key] = stableFirestoreValue(value[key]);
      return out;
    }, {});
  }
  return value;
}

function firestoreWriteFingerprint(collectionName: string, id: string, data: any): string {
  return collectionName + '/' + id + '::' + JSON.stringify(stableFirestoreValue(data));
}

`;

  if (!source.includes('const recentFirestoreWrites')) {
    source = source.replace(marker, helper + marker);
  }

  const oldSave = '  await setDoc(doc(db, collName, targetId), docData, { merge: true });\n  return targetId;';
  const newSave = `  const writeKey = firestoreWriteFingerprint(collName, targetId, docData);
  if (recentFirestoreWrites.get(collName + '/' + targetId) !== writeKey) {
    await setDoc(doc(db, collName, targetId), docData, { merge: true });
    recentFirestoreWrites.set(collName + '/' + targetId, writeKey);
  }
  return targetId;`;
  source = source.replace(oldSave, newSave);

  return source;
}, 'firestoreService duplicate-write guard');

// Protect the generic helper write path (especially business settings) from
// repeatedly writing identical state during initialization/re-hydration.
patchFile('src/lib/firebase-helpers.ts', (source) => {
  const marker = 'export const upsertDocument = async (table: string, id: string, data: any) => {';
  const helper = `const recentHelperWrites = new Map<string, string>();

function helperWriteFingerprint(table: string, id: string, data: any): string {
  const normalize = (value: any): any => {
    if (Array.isArray(value)) return value.map(normalize);
    if (value && typeof value === 'object') {
      return Object.keys(value).sort().reduce((out: any, key) => {
        if (key !== 'updated_at') out[key] = normalize(value[key]);
        return out;
      }, {});
    }
    return value;
  };
  return table + '/' + id + '::' + JSON.stringify(normalize(data));
}

`;
  if (!source.includes('const recentHelperWrites')) {
    source = source.replace(marker, helper + marker);
  }

  const oldWrite = '    await setDoc(doc(db, table, id), enrichedData, { merge: true });';
  const newWrite = `    const writeKey = helperWriteFingerprint(table, id, enrichedData);
    const cacheKey = table + '/' + id;
    if (recentHelperWrites.get(cacheKey) !== writeKey) {
      await setDoc(doc(db, table, id), enrichedData, { merge: true });
      recentHelperWrites.set(cacheKey, writeKey);
    }`;
  source = source.replace(oldWrite, newWrite);

  return source;
}, 'firebase-helpers duplicate-write guard');

// Full legacy recovery is expensive. Normal cross-device synchronization is
// already handled by the realtime listeners, so automatic recovery runs only
// once per browser session/account. Explicit manual restore remains untouched.
patchFile('src/App.tsx', (source) => {
  const oldCall = `            const wasRestored = await fetchAndRestoreCloudBackup(user.email, passcode, false);
            if (wasRestored) {`;
  const newCall = `            const recoveryKey = 'barakah_cloud_recovery_' + String(user.email || '').trim().toLowerCase();
            const recoveryAlreadyDone = typeof sessionStorage !== 'undefined' && sessionStorage.getItem(recoveryKey) === '1';
            const wasRestored = recoveryAlreadyDone ? false : await fetchAndRestoreCloudBackup(user.email, passcode, false);
            if (wasRestored && typeof sessionStorage !== 'undefined') sessionStorage.setItem(recoveryKey, '1');
            if (wasRestored) {`;
  return source.replace(oldCall, newCall);
}, 'App automatic recovery throttle');

