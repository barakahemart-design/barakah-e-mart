const fs = require('fs');

function patchFile(path, transform, label) {
  const source = fs.readFileSync(path, 'utf8');
  const next = transform(source);
  if (next !== source) {
    fs.writeFileSync(path, next, 'utf8');
    console.log(`[Firestore quota guard] Patched ${label}`);
  } else {
    console.log(`[Firestore quota guard] No change needed for ${label}`);
  }
}

// Keep the existing memory-only cache strategy: persistent multi-tab
// coordination previously caused browser storage quota problems. Remove only
// the old startup connectivity probe, which performed a billed document read.
patchFile('src/lib/firebase.ts', (source) => source.replace(
  /\nasync function testConnection\(\) \{[\s\S]*?\n\}\n\ntestConnection\(\);\s*$/,
  '\n'
), 'firebase startup probe');

// Suppress only immediate duplicate saves caused by re-hydration/autosave cycles.
// The short TTL prevents a stale in-memory fingerprint from blocking later edits.
// updated_at is ignored because it is generated by the save path.
patchFile('src/lib/firestoreService.ts', (source) => {
  const marker = 'function createSubscription(collName: string) {';
  const helper = `const recentFirestoreWrites = new Map<string, { fingerprint: string; timestamp: number }>();
const DUPLICATE_WRITE_WINDOW_MS = 1200;

function stableFirestoreValue(value: any): any {
  if (Array.isArray(value)) return value.map(stableFirestoreValue);
  if (value && typeof value === 'object') {
    return Object.keys(value).sort().reduce((out: any, key) => {
      if (key !== 'updated_at') out[key] = stableFirestoreValue(value[key]);
      return out;
    }, {});
  }
  return value;
}

function firestoreWriteFingerprint(collectionName: string, id: string, data: any): string {
  return collectionName + '/' + id + '::' + JSON.stringify(stableFirestoreValue(data));
}

function shouldSkipRecentFirestoreWrite(cacheKey: string, fingerprint: string): boolean {
  const previous = recentFirestoreWrites.get(cacheKey);
  if (!previous) return false;
  if (previous.fingerprint === fingerprint && Date.now() - previous.timestamp < DUPLICATE_WRITE_WINDOW_MS) return true;
  recentFirestoreWrites.delete(cacheKey);
  return false;
}

function rememberFirestoreWrite(cacheKey: string, fingerprint: string): void {
  const now = Date.now();
  recentFirestoreWrites.set(cacheKey, { fingerprint, timestamp: now });
  if (recentFirestoreWrites.size > 500) {
    for (const [key, value] of recentFirestoreWrites) {
      if (now - value.timestamp >= DUPLICATE_WRITE_WINDOW_MS) recentFirestoreWrites.delete(key);
    }
    while (recentFirestoreWrites.size > 500) {
      const oldestKey = recentFirestoreWrites.keys().next().value;
      if (!oldestKey) break;
      recentFirestoreWrites.delete(oldestKey);
    }
  }
}
`;

  if (!source.includes('const recentFirestoreWrites')) {
    source = source.replace(marker, helper + marker);
  }

  const oldSave = '  await setDoc(doc(db, collName, targetId), docData, { merge: true });\n  return targetId;';
  const newSave = `  const cacheKey = collName + '/' + targetId;
  const writeKey = firestoreWriteFingerprint(collName, targetId, docData);
  if (!shouldSkipRecentFirestoreWrite(cacheKey, writeKey)) {
    await setDoc(doc(db, collName, targetId), docData, { merge: true });
    rememberFirestoreWrite(cacheKey, writeKey);
  }
  return targetId;`;
  source = source.replace(oldSave, newSave);

  return source;
}, 'firestoreService duplicate-write guard');

// Protect the generic helper write path (especially business settings) from
// repeatedly writing identical state during initialization/re-hydration.
patchFile('src/lib/firebase-helpers.ts', (source) => {
  const marker = 'export const upsertDocument = async (table: string, id: string, data: any) => {';
  const helper = `const recentHelperWrites = new Map<string, { fingerprint: string; timestamp: number }>();
const HELPER_DUPLICATE_WRITE_WINDOW_MS = 1200;

function helperWriteFingerprint(table: string, id: string, data: any): string {
  const normalize = (value: any): any => {
    if (Array.isArray(value)) return value.map(normalize);
    if (value && typeof value === 'object') {
      return Object.keys(value).sort().reduce((out: any, key) => {
        if (key !== 'updated_at') out[key] = normalize(value[key]);
        return out;
      }, {});
    }
    return value;
  };
  return table + '/' + id + '::' + JSON.stringify(normalize(data));
}

function shouldSkipRecentHelperWrite(cacheKey: string, fingerprint: string): boolean {
  const previous = recentHelperWrites.get(cacheKey);
  if (!previous) return false;
  if (previous.fingerprint === fingerprint && Date.now() - previous.timestamp < HELPER_DUPLICATE_WRITE_WINDOW_MS) return true;
  recentHelperWrites.delete(cacheKey);
  return false;
}

function rememberHelperWrite(cacheKey: string, fingerprint: string): void {
  const now = Date.now();
  recentHelperWrites.set(cacheKey, { fingerprint, timestamp: now });
  if (recentHelperWrites.size > 500) {
    for (const [key, value] of recentHelperWrites) {
      if (now - value.timestamp >= HELPER_DUPLICATE_WRITE_WINDOW_MS) recentHelperWrites.delete(key);
    }
    while (recentHelperWrites.size > 500) {
      const oldestKey = recentHelperWrites.keys().next().value;
      if (!oldestKey) break;
      recentHelperWrites.delete(oldestKey);
    }
  }
}
`;
  if (!source.includes('const recentHelperWrites')) {
    source = source.replace(marker, helper + marker);
  }

  const oldWrite = '    await setDoc(doc(db, table, id), enrichedData, { merge: true });';
  const newWrite = `    const writeKey = helperWriteFingerprint(table, id, enrichedData);
    const cacheKey = table + '/' + id;
    if (!shouldSkipRecentHelperWrite(cacheKey, writeKey)) {
      await setDoc(doc(db, table, id), enrichedData, { merge: true });
      rememberHelperWrite(cacheKey, writeKey);
    }`;
  source = source.replace(oldWrite, newWrite);

  return source;
}, 'firebase-helpers duplicate-write guard');

// Full legacy recovery is expensive. Normal cross-device synchronization is
// already handled by the realtime listeners, so automatic recovery runs only
// once per browser session/account. Explicit manual restore remains untouched.
patchFile('src/App.tsx', (source) => {
  const oldCall = `            const wasRestored = await fetchAndRestoreCloudBackup(user.email, passcode, false);
            if (wasRestored) {`;
  const newCall = `            const recoveryKey = 'barakah_cloud_recovery_' + String(user.email || '').trim().toLowerCase();
            const recoveryAlreadyDone = typeof sessionStorage !== 'undefined' && sessionStorage.getItem(recoveryKey) === '1';
            const wasRestored = recoveryAlreadyDone ? false : await fetchAndRestoreCloudBackup(user.email, passcode, false);
            if (wasRestored && typeof sessionStorage !== 'undefined') sessionStorage.setItem(recoveryKey, '1');
            if (wasRestored) {`;
  return source.replace(oldCall, newCall);
}, 'App automatic recovery throttle');

